/* ---------- Panel ---------- */

export type ReviewDecision = "accepted" | "edited" | "dismissed";

export function AiPanel({
  title,
  meta,
  children,
  actions,
  footer,
  className,
  onRegenerate,
  busy,
}: {
  title: string;
  meta?: AiMeta;
  children: React.ReactNode;
  actions?: React.ReactNode;
  footer?: React.ReactNode;
  className?: string;
  onRegenerate?: () => void;
  busy?: boolean;
}) {
  return (
    <section className={cn("flex min-w-0 flex-col overflow-hidden rounded-xl border border-info/25 bg-card", className)} aria-label={title}>
      <div className="flex flex-wrap items-center gap-2 border-b border-info/15 bg-info-soft/40 px-4 py-2.5">
        <Sparkles className="size-4 text-info" strokeWidth={ICON_STROKE} aria-hidden />
        <h2 className="mr-auto text-sm font-medium">{title}</h2>
        <AiDisclaimer />
        {actions}
        {onRegenerate && (
          <Button variant="ghost" size="icon-sm" onClick={onRegenerate} disabled={busy} aria-label="Regenerate">
            <RotateCw strokeWidth={ICON_STROKE} />
          </Button>
        )}
      </div>
      <div className="min-w-0 flex-1">{children}</div>
      {(meta || footer) && (
        <div className="space-y-2 border-t px-4 py-2.5">
          {meta && <ConfidenceMeter value={meta.confidence} />}
          {footer}
          {meta && <AiSources meta={meta} />}
        </div>
      )}
    </section>
  );
}

/** Explicit clinician review. AI output is never applied without it. */
export function ReviewBar({ onAccept, onEdit, onDismiss, decision, acceptLabel = "Accept" }: { onAccept?: () => void; onEdit?: () => void; onDismiss?: () => void; decision?: ReviewDecision; acceptLabel?: string }) {
  if (decision)
    return (
      <p className="flex items-center gap-1.5 text-xs text-muted-foreground" role="status">
        {decision === "dismissed" ? <X className="size-3.5" /> : <Check className="size-3.5 text-stable" />}
        {decision === "accepted" ? "Accepted by clinician" : decision === "edited" ? "Edited and accepted by clinician" : "Dismissed by clinician"}
      </p>
    );
  return (
    <div className="flex flex-wrap items-center gap-2">
      {onAccept && (
        <Button size="sm" onClick={onAccept}>
          <Check /> {acceptLabel}
        </Button>
      )}
      {onEdit && (
        <Button size="sm" variant="outline" onClick={onEdit}>
          <Pencil /> Edit before use
        </Button>
      )}
      {onDismiss && (
        <Button size="sm" variant="ghost" onClick={onDismiss}>
          Dismiss
        </Button>
      )}
    </div>
  );
}

/* ---------- Risk scores ---------- */

const LEVEL_TONE = { Low: "stable", Moderate: "warning", High: "critical", Critical: "critical" } as const;

export function RiskScoreCard({ score, compact = false }: { score: RiskScore; compact?: boolean }) {
  const [open, setOpen] = useState(!compact);
  const maxPts = Math.max(3, ...score.factors.map((f) => f.points));
  return (
    <div className="rounded-lg border bg-card">
      <button type="button" onClick={() => setOpen((v) => !v)} aria-expanded={open} className="flex w-full items-center gap-3 px-3 py-2.5 text-left">
        <div className="min-w-0 flex-1">
          <p className="truncate text-xs text-muted-foreground">{score.label}</p>
          <p className="flex items-baseline gap-2">
            <span className="text-xl font-semibold">{score.display}</span>
            <span className="text-[11px] text-muted-foreground">{score.scale}</span>
          </p>
        </div>
        <StatusBadge tone={LEVEL_TONE[score.level]}>{score.level}</StatusBadge>
      </button>
      <AnimatePresence initial={false}>
        {open && (
          <motion.div initial={{ opacity: 0, height: 0 }} animate={{ opacity: 1, height: "auto" }} exit={{ opacity: 0, height: 0 }} className="overflow-hidden">
            <div className="space-y-3 border-t px-3 py-3">
              {score.factors.length ? (
                <ul className="space-y-1.5" aria-label="Contributing factors">
                  {score.factors.map((f) => (
                    <li key={f.label} className="grid grid-cols-[1fr_auto] items-center gap-x-3 text-xs">
                      <span className="truncate">
                        {f.label} <span className="text-muted-foreground">({f.value})</span>
                      </span>
                      <span className="flex items-center gap-1.5">
                        <span aria-hidden className="h-1.5 rounded-full bg-info" style={{ width: `${(f.points / maxPts) * 40}px` }} />
                        <span className="num w-6 text-right">+{f.points}</span>
                      </span>
                    </li>
                  ))}
                </ul>
              ) : (
                <p className="text-xs text-muted-foreground">No contributing factors identified.</p>
              )}
              <p className="text-xs leading-relaxed">
                <span className="font-medium">Suggested response: </span>
                {score.recommendation}
              </p>
              <ConfidenceMeter value={score.meta.confidence} />
            </div>
          </motion.div>
        )}
      </AnimatePresence>
    </div>
  );
}
