export function confidenceLabel(c: number): "High" | "Moderate" | "Low" {
  return c >= 0.85 ? "High" : c >= 0.7 ? "Moderate" : "Low";
}

/** Meter: accent fill on a lighter step of the same hue (dataviz meter spec). */
export function ConfidenceMeter({ value, className }: { value: number; className?: string }) {
  const pct = Math.round(value * 100);
  const label = confidenceLabel(value);
  return (
    <div className={cn("flex items-center gap-2 text-xs", className)}>
      <span className="text-muted-foreground">Confidence</span>
      <span role="meter" aria-valuemin={0} aria-valuemax={100} aria-valuenow={pct} aria-label={`Model confidence ${pct}%`} className="relative h-1.5 w-16 overflow-hidden rounded-full bg-info-soft">
        <span className={cn("absolute inset-y-0 left-0 rounded-full", label === "Low" ? "bg-warning" : "bg-info")} style={{ width: `${pct}%` }} />
      </span>
      <span className="font-medium tabular">
        {pct}% <span className="font-normal text-muted-foreground">{label.toLowerCase()}</span>
      </span>
    </div>
  );
}

/* ---------- Markdown-lite rendering for streamed text ---------- */

function inline(text: string): React.ReactNode[] {
  return text.split(/(\*\*[^*]+\*\*)/g).map((part, i) => (part.startsWith("**") && part.endsWith("**") ? <strong key={i} className="font-semibold">{part.slice(2, -2)}</strong> : part));
}

export function MarkdownLite({ text, streaming }: { text: string; streaming?: boolean }) {
  const blocks: React.ReactNode[] = [];
  const lines = text.split("\n");
  let list: string[] = [];
  const flush = (key: string) => {
    if (list.length) {
      blocks.push(
        <ul key={key} className="space-y-1 pl-4">
          {list.map((l, i) => (
            <li key={i} className="list-disc marker:text-subtle-foreground">
              {inline(l)}
            </li>
          ))}
        </ul>,
      );
      list = [];
    }
  };
  lines.forEach((line, i) => {
    if (line.startsWith("- ")) {
      list.push(line.slice(2));
      return;
    }
    flush(`l${i}`);
    if (line.startsWith("## ")) blocks.push(<h3 key={i} className="pt-2 text-xs font-semibold tracking-wide text-muted-foreground first:pt-0">{line.slice(3)}</h3>);
    else if (line.trim()) blocks.push(<p key={i}>{inline(line)}</p>);
  });
  flush("end");
  return (
    <div className="space-y-2 text-sm leading-relaxed">
      {blocks}
      {streaming && <span aria-hidden className="inline-block h-4 w-1.5 translate-y-0.5 animate-pulse rounded-sm bg-info" />}
    </div>
  );
}

/* ---------- Streaming hook ---------- */

type Phase = "idle" | "analyzing" | "streaming" | "done" | "error";

export function useAiStream(start: (signal: AbortSignal) => Promise<AiStream>) {
  const [phase, setPhase] = useState<Phase>("idle");
  const [text, setText] = useState("");
  const [meta, setMeta] = useState<AiMeta>();
  const [error, setError] = useState<unknown>();
  const ctrl = useRef<AbortController | undefined>(undefined);

  const run = useCallback(async () => {
    ctrl.current?.abort();
    const c = new AbortController();
    ctrl.current = c;
    setPhase("analyzing");
    setText("");
    setError(undefined);
    try {
      const res = await start(c.signal);
      if (c.signal.aborted) return;
      setMeta(res.meta);
      setPhase("streaming");
      let acc = "";
      for await (const chunk of res.stream) {
        if (c.signal.aborted) return;
        acc += chunk;
        setText(acc);
      }
      setPhase("done");
    } catch (e) {
      if (!c.signal.aborted) {
        setError(e);
        setPhase("error");
      }
    }
  }, [start]);

  useEffect(() => () => ctrl.current?.abort(), []);
  const reset = () => {
    ctrl.current?.abort();
    setPhase("idle");
    setText("");
  };
  return { phase, text, meta, error, run, reset };
}

/* ---------- Analyzing state ---------- */

export function Analyzing({ steps, label = "Analyzing" }: { steps: string[]; label?: string }) {
  const [i, setI] = useState(0);
  useEffect(() => {
    const t = setInterval(() => setI((x) => Math.min(steps.length - 1, x + 1)), 520);
    return () => clearInterval(t);
  }, [steps.length]);
  return (
    <div className="space-y-3 p-4" role="status" aria-live="polite">
      <div className="flex items-center gap-2 text-sm font-medium">
        <span className="relative flex size-2">
          <span className="absolute inline-flex size-full animate-ping rounded-full bg-info opacity-60 motion-reduce:hidden" />
          <span className="relative inline-flex size-2 rounded-full bg-info" />
        </span>
        {label}…
      </div>
      <ul className="space-y-1.5 text-xs text-muted-foreground">
        {steps.map((s, idx) => (
          <li key={s} className={cn("flex items-center gap-2 transition-opacity", idx > i && "opacity-35")}>
            {idx < i ? <Check className="size-3.5 text-stable" /> : <span className="size-3.5" aria-hidden />}
            {s}
          </li>
        ))}
      </ul>
      <div className="space-y-2 pt-1" aria-hidden>
        {[92, 78, 85].map((w) => (
          <div key={w} className="h-3 animate-pulse rounded bg-muted" style={{ width: `${w}%` }} />
        ))}
      </div>
    </div>
  );
}

