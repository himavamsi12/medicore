export const DRUGS: Drug[] = rows.map((r, i) => {
  const [brand, generic, strength, form, drugClass, manufacturer, schedule, gstRate, mrp, packSize, highAlert] = r;
  return {
    id: `DRG-${String(i + 1).padStart(4, "0")}`,
    brand,
    generic,
    strength,
    form,
    drugClass,
    manufacturer,
    schedule,
    gstRate,
    hsn: form === "Injection" || form === "Infusion" ? "30042019" : "30049099",
    mrp,
    packSize,
    highAlert,
    reorderLevel: form === "Injection" || form === "Infusion" ? 40 : form === "Tablet" || form === "Capsule" ? 300 : 25,
  };
});

export function drugByBrand(brand: string): Drug {
  const d = DRUGS.find((x) => x.brand === brand);
  if (!d) throw new Error(`Formulary is missing ${brand}`);
  return d;
}
